CREATE TABLE campus_certification_revocation (
  user_id BIGINT NOT NULL,
  revision BIGINT NOT NULL,
  admin_id BIGINT NOT NULL,
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  reason VARCHAR(2000) NOT NULL,
  occurred_at DATETIME(6) NOT NULL,
  PRIMARY KEY (user_id, revision),
  UNIQUE KEY uq_cert_revocation_request (admin_id, request_id),
  FOREIGN KEY (user_id) REFERENCES campus_certification(user_id),
  FOREIGN KEY (admin_id) REFERENCES community_admin(id),
  CHECK (revision > 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

