ALTER TABLE campus_certification
  ADD revision BIGINT NOT NULL DEFAULT 1,
  ADD CONSTRAINT ck_cert_revision CHECK(revision>0);

ALTER TABLE auth_email_gate DROP CHECK ck_gate_purpose,
  ADD CONSTRAINT ck_gate_purpose CHECK(purpose IN ('REGISTER','PASSWORD_RESET','CAMPUS_REVERIFY'));
ALTER TABLE email_challenge DROP CHECK ck_challenge_purpose,
  ADD reverify_session_id BIGINT NULL,
  ADD reverify_revision BIGINT NULL,
  ADD CONSTRAINT ck_challenge_purpose CHECK(purpose IN ('REGISTER','PASSWORD_RESET','CAMPUS_REVERIFY')),
  ADD CONSTRAINT ck_reverify_binding CHECK(
    (purpose='CAMPUS_REVERIFY' AND reverify_session_id IS NOT NULL AND reverify_revision IS NOT NULL)
    OR (purpose<>'CAMPUS_REVERIFY' AND reverify_session_id IS NULL AND reverify_revision IS NULL));

ALTER TABLE business_audit
  DROP CHECK ck_audit_action,
  DROP CHECK ck_audit_object,
  DROP CHECK ck_audit_before,
  DROP CHECK ck_audit_after,
  ADD CONSTRAINT ck_audit_action CHECK(action IN ('PROFILE_UPDATE','CONTACT_UPDATE','ARTICLE_PUBLISH','ARTICLE_UNPUBLISH','ARTICLE_RESTORE','ARTICLE_DELETE','COMMENT_CREATE','COMMENT_DELETE','LIKE_SET','LIKE_CANCEL','FAVORITE_SET','FAVORITE_CANCEL','READING_START','LOGIN_REWARD','READING_REWARD','ARTICLE_COIN','CASE_SUBMIT','CASE_IMAGE_UPLOAD','CASE_CLAIM','CASE_RELEASE','CASE_DECISION','CONTRIBUTION_INVALIDATE','CAMPUS_REVERIFY')),
  ADD CONSTRAINT ck_audit_object CHECK(object_type IN ('PROFILE','CONTACT','ARTICLE','COMMENT','LIKE','FAVORITE','READING','WALLET','CASE','CASE_IMAGE','CONTRIBUTION','CERTIFICATION')),
  ADD CONSTRAINT ck_audit_before CHECK(before_state IS NULL OR before_state IN ('ENABLED','DISABLED','DRAFT','PUBLISHED','AUTHOR_OFFLINE','ADMIN_HIDDEN','DELETED','VISIBLE','OPEN','PROCESSING','NEEDS_ACTION','CLOSED','REVOKED','VALID')),
  ADD CONSTRAINT ck_audit_after CHECK(after_state IS NULL OR after_state IN ('ENABLED','DISABLED','DRAFT','PUBLISHED','AUTHOR_OFFLINE','ADMIN_HIDDEN','DELETED','VISIBLE','OPEN','PROCESSING','NEEDS_ACTION','CLOSED','REVOKED','VALID'));
